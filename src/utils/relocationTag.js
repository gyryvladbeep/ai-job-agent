/*
 * Лёгкая эвристика: ищем явные признаки релокации/визовой поддержки
 * в тексте вакансии. Это дополнительная метка поверх обычного QA-
 * фильтра, а не замена ему и не отдельный фильтр -- специально
 * сделано так, чтобы не трогать основной поток вакансий (по запросу
 * пользователя), только добавлять один необязательный штрих в
 * уведомление, когда сигнал реально есть.
 *
 * Исправлено 2026-09-22 (найдено новым тестом test/relocationTag.test.js):
 * русские фразы раньше проверялись в словарной форме ("визовая
 * поддержка"), но реальный текст вакансии почти всегда склоняет их
 * ("визовую поддержку", "поможем с релокацией") -- подстрока не
 * находилась, и сигнал молча пропадал. Ключевые слова заменены на
 * неизменяемые основы (например "визов" вместо "визовая поддержка"),
 * которые остаются подстрокой при любом падеже/числе.
 */

const RELOCATION_KEYWORDS = [
    "relocation",
    "relocation package",
    "relocation support",
    "relocation assistance",
    "visa sponsorship",
    "visa support",
    "work permit",
    "sponsor a visa",
    "relocate",

    "релокац", // релокация / релокацию / релокации / релокационный...
    "визов", // визовая / визовую / визовой / визовое поддержка...
    "помощь с виз", // помощь с визой / визу / визами
    "оформление визы",
    "оформить визу",
    "переезд" // переезд / переезда / переездом / переезде
];

function normalize(text) {
    return String(text || "")
        .toLowerCase()
        .replace(/ё/g, "е")
        .replace(/\s+/g, " ")
        .trim();
}

function hasRelocationSignal(job) {
    const haystack = normalize(
        `${job.position || ""} ${job.description || ""}`
    );

    if (!haystack) {
        return false;
    }

    return RELOCATION_KEYWORDS.some(keyword =>
        haystack.includes(normalize(keyword))
    );
}

module.exports = {
    hasRelocationSignal
};
